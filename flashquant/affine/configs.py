@dataclass(frozen=True)
class KernelConfig:
    tile: tuple
    family: str
    width: int  # warp K for CooperativeKernel; cohort count for CohortKernel
    overrides: dict

    def value(self, name):
        return self.overrides.get(name, DEFAULTS[name])

    @property
    def header(self):
        return "cooperative.cuh" if self.family == "CooperativeKernel" else "cohorts.cuh"

    def specialization(self):
        args = [*self.tile, self.width]
        if self.family == "CooperativeKernel":
            args.extend(self.value(k) for k in DEFAULTS)
        return self.family + "<" + ",".join(map(str, args)) + ">"


def warp_k(tile, wk, **options):
    unknown = options.keys() - DEFAULTS.keys()
    if unknown:
        raise ValueError(f"unknown cooperative kernel options: {unknown}")
    return KernelConfig(tile, "CooperativeKernel", wk, options)


def cohort(tile, count):
    return KernelConfig(tile, "CohortKernel", count, {})


